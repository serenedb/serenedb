#!/usr/bin/env python3
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "third_party", "licenses.json")
DOC = os.path.join(ROOT, "third_party", "LICENSES.md")
CONTRIBUTORS = os.path.join(ROOT, "resources", "contributors.txt")
BEGIN = ("<!-- Generated by scripts/licenses.py from licenses.json: "
         "edit that file and rerun the script. -->")
END = "<!-- End of the generated section. -->"
REQUIRED = {"name", "url", "license", "files"}
ALLOWED = REQUIRED | {"paths"}
UNKNOWN = "NOASSERTION"


def under(path, prefix):
    return path == prefix or path.startswith(prefix + "/")


def plain(path):
    return (bool(path) and not os.path.isabs(path)
            and os.path.normpath(path) == path and not path.startswith(".."))


def load():
    with open(MANIFEST, encoding="utf-8") as f:
        manifest = json.load(f)
    problems = []
    components = manifest.get("components", [])
    names = [component.get("name", "") for component in components]
    if names != sorted(names, key=str.casefold):
        problems.append("components are not sorted by name")
    if len(set(names)) != len(names):
        problems.append("two components share a name")
    for component in components:
        name = component.get("name", "?")
        keys = set(component)
        if not REQUIRED <= keys or not keys <= ALLOWED:
            problems.append(f"{name}: needs {sorted(REQUIRED)}, may add 'paths'")
            continue
        if not component["files"] and component["license"] != UNKNOWN:
            problems.append(f"{name}: no license file, so its license is {UNKNOWN}")
        for path in component["files"] + component.get("paths", []):
            if not plain(path):
                problems.append(f"{name}: '{path}' is not a plain relative path")
    for path in manifest.get("own", []):
        if not plain(path) or not under(path, "third_party"):
            problems.append(f"own: '{path}' is not a directory under third_party")
    return manifest, problems


def section(components):
    groups = {}
    for component in components:
        groups.setdefault(component["license"], []).append(component)
    lines = [BEGIN, "", "## Built into serened", "",
             "SereneDB and the libraries below are built into serened. "
             "`SELECT * FROM serenedb_licenses` lists the ones a server was "
             "built with, with the text of each license file.", ""]
    for license in sorted(groups, key=str.casefold):
        lines += [f"### {license}", ""]
        for component in groups[license]:
            files = ", ".join(f"`{path}`" for path in component["files"])
            lines.append(f"* [{component['name']}]({component['url']}): "
                         f"{files or 'no license file'}")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def spliced(text, components):
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < start:
        sys.exit(f"{DOC} lacks the markers of its generated section")
    return text[:start] + section(components) + text[stop + len(END):]


def submodules():
    paths = []
    with open(os.path.join(ROOT, ".gitmodules"), encoding="utf-8") as f:
        for line in f:
            key, _, value = line.strip().partition("=")
            if key.strip() == "path":
                paths.append(value.strip())
    return paths


def checked_out(path, modules):
    for module in modules:
        if under(path, module):
            directory = os.path.join(ROOT, module)
            return os.path.isdir(directory) and bool(os.listdir(directory))
    return True


def check():
    manifest, problems = load()
    modules = submodules()
    for component in manifest.get("components", []):
        for path in component.get("files", []):
            if checked_out(path, modules) and not os.path.isfile(os.path.join(ROOT, path)):
                problems.append(f"{component.get('name')}: {path} does not exist")
    with open(DOC, encoding="utf-8") as f:
        text = f.read()
    if not problems and spliced(text, manifest["components"]) != text:
        problems.append(f"{DOC} is stale: run scripts/licenses.py")
    for problem in problems:
        print(f"{MANIFEST}: {problem}", file=sys.stderr)
    return 1 if problems else 0


def regenerate():
    manifest, problems = load()
    if problems:
        for problem in problems:
            print(f"{MANIFEST}: {problem}", file=sys.stderr)
        return 1
    with open(DOC, encoding="utf-8") as f:
        text = f.read()
    updated = spliced(text, manifest["components"])
    if updated != text:
        with open(DOC, "w", encoding="utf-8") as f:
            f.write(updated)
    return 0


def relative(path, roots):
    for root in roots:
        if path == root or path.startswith(root + os.sep):
            return os.path.relpath(path, root).replace(os.sep, "/")
    return None


def read_text(path):
    with open(os.path.join(ROOT, path), "rb") as f:
        data = f.read()
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        text = data.decode("latin-1")
    return text.replace("\r\n", "\n")


def c_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def raw_string(text):
    tag = "sdb"
    while f"){tag}\"" in text:
        tag += "x"
    return f'R"{tag}({text}){tag}"'


def source(rows, contributors):
    names = {}
    lines = ['#include "server/utils/credits.h"', "", "#include <array>", "",
             "namespace sdb::credits {", "namespace {", ""]
    for _, _, text in rows:
        if text is not None and text not in names:
            names[text] = f"kText{len(names)}"
            lines.append(f"constexpr std::string_view {names[text]} = {raw_string(text)};")
            lines.append("")
    lines.append(f"constexpr std::array<License, {len(rows)}> kLicenses{{{{")
    for component, path, text in rows:
        fields = [c_string(component["name"]), c_string(component["license"]),
                  c_string(component["url"]),
                  c_string(path) if path else "{}",
                  names[text] if text is not None else "{}"]
        lines.append(f"  License{{{', '.join(fields)}}},")
    lines += ["}};", ""]
    lines.append(f"constexpr std::array<std::string_view, {len(contributors)}> "
                 f"kContributors{{{{")
    lines += [f"  {c_string(name)}," for name in contributors]
    lines += ["}};", "", "}  // namespace", "",
              "std::span<const License> Licenses() noexcept { return kLicenses; }",
              "",
              "std::span<const std::string_view> Contributors() noexcept {",
              "  return kContributors;", "}", "", "}  // namespace sdb::credits", ""]
    return "\n".join(lines)


def build(args):
    manifest, problems = load()
    if problems:
        for problem in problems:
            print(f"{MANIFEST}: {problem}", file=sys.stderr)
        return 1
    components = manifest["components"]
    roots = sorted({os.path.normpath(args.binary_dir), os.path.normpath(args.source_dir)},
                   key=len, reverse=True)
    covers = sorted(((path, component["name"]) for component in components
                     for path in component.get("paths", [])),
                    key=lambda entry: len(entry[0]), reverse=True)
    used, missing = set(), set()
    with open(args.linked, encoding="utf-8") as f:
        linked = [line.strip() for line in f if line.strip()]
    for directory in linked:
        rel = relative(os.path.normpath(directory), roots)
        if (rel is None or rel == "third_party" or not under(rel, "third_party")
                or any(under(rel, own) for own in manifest.get("own", []))):
            continue
        name = next((name for path, name in covers if under(rel, path)), None)
        if name is None:
            missing.add(rel)
        else:
            used.add(name)
    if missing:
        print(f"{MANIFEST} has no component for these directories serened is "
              "built from; add theirs:", file=sys.stderr)
        for rel in sorted(missing):
            print(f"  {rel}", file=sys.stderr)
        return 1
    absent = sorted(component["name"] for component in components
                    if component.get("paths") and component["name"] not in used)
    if absent:
        print("components this build leaves out: " + ", ".join(absent),
              file=sys.stderr)
    rows, read = [], [MANIFEST, CONTRIBUTORS, os.path.abspath(__file__)]
    for component in components:
        if component.get("paths") and component["name"] not in used:
            continue
        if not component["files"]:
            rows.append((component, None, None))
        for path in component["files"]:
            if not os.path.isfile(os.path.join(ROOT, path)):
                print(f"{component['name']}: {path} does not exist", file=sys.stderr)
                return 1
            rows.append((component, path, read_text(path)))
            read.append(os.path.join(ROOT, path))
    with open(CONTRIBUTORS, encoding="utf-8") as f:
        contributors = [line for line in f.read().splitlines() if line]
    text = source(rows, contributors)
    try:
        with open(args.output, encoding="utf-8") as f:
            current = f.read()
    except FileNotFoundError:
        current = None
    if current != text:
        os.makedirs(os.path.dirname(args.output), exist_ok=True)
        with open(args.output, "w", encoding="utf-8") as f:
            f.write(text)
    print("\n".join(read))
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="third_party/licenses.json lists the components serened is "
        "built from. Without arguments, rewrite the section of "
        "third_party/LICENSES.md that lists them; --check checks the manifest "
        "and that section; 'build' is what CMake runs while configuring.")
    parser.add_argument("--check", action="store_true",
                        help="check the manifest and LICENSES.md, write nothing")
    commands = parser.add_subparsers(dest="command")
    builder = commands.add_parser(
        "build", help="map the directories serened is built from to components, "
        "fail on any no component covers, and write the C++ source that holds "
        "the licenses and the contributors; print the files it read")
    builder.add_argument("--linked", required=True,
                         help="file with one directory serened is built from per line")
    builder.add_argument("--source-dir", required=True)
    builder.add_argument("--binary-dir", required=True)
    builder.add_argument("--output", required=True)
    args = parser.parse_args()
    if args.command == "build":
        return build(args)
    return check() if args.check else regenerate()


if __name__ == "__main__":
    sys.exit(main())
