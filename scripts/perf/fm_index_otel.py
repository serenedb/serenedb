import argparse
import json
import os
from pathlib import Path
import re
import shutil
import statistics
import subprocess
import tempfile
import time

import fm_index as common


SOURCE = "https://public-pme.s3.eu-west-3.amazonaws.com/text_bench/part_000.parquet"
SEARCHBENCH_REVISION = "3c8e3928619adc0e0b58c48df89dc8a68b4cfc1b"
QUERY_SOURCE = ("https://github.com/serenedb/searchbench/blob/" + SEARCHBENCH_REVISION
                + "/serenedb/queries.sql")
CORPUS_DESCRIPTION = "synthetic OpenTelemetry logs generated by the OpenTelemetry demo application"
CORPUS_DESCRIPTION_SOURCE = "https://github.com/ClickHouse/TextBench/blob/main/README.md"
NATIVE_ANALYZER = "split_by_non_alpha(case := 'lower', break := 'ascii')"
CASES = [
    ("q27_infix_count", "count", "like", "%nnec%", "Q27"),
    ("q27_infix_locate", "locate", "like", "%nnec%", "Q27 predicate, complete sorted sample IDs"),
    ("q25_prefix_count", "count", "like", "conn%", "Q25"),
    ("q26_suffix_count", "count", "like", "%tion", "Q26"),
    ("q01_term_count", "count", "term", "error", "Q01"),
    ("control_absent_count", "count", "like", "%zzzzfmindexnotpresentzzzz%", "additional absent control"),
]


def prepare(args):
    import pyarrow.parquet as pq
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if args.output.exists():
        raise RuntimeError(f"refusing to replace sample: {args.output}")
    source = common.HttpRangeFile(args.source)
    temporary = None
    try:
        parquet = pq.ParquetFile(source)
        if not 0 < args.rows <= parquet.metadata.num_rows:
            raise ValueError("sample row count is outside the source")
        body_name = next(name for name in parquet.schema_arrow.names if name.lower() == "body")
        descriptor, temporary_name = tempfile.mkstemp(dir=args.output.parent, suffix=".parquet")
        os.close(descriptor)
        temporary = Path(temporary_name)
        remaining = args.rows
        groups = []
        writer = None
        try:
            for group in range(parquet.num_row_groups):
                table = parquet.read_row_group(group, columns=[body_name])
                table = table.slice(0, min(remaining, table.num_rows)).rename_columns(["Body"])
                if writer is None:
                    writer = pq.ParquetWriter(temporary, table.schema, compression="zstd")
                writer.write_table(table)
                groups.append({"row_group": group, "rows": table.num_rows})
                remaining -= table.num_rows
                if remaining == 0:
                    break
        finally:
            if writer is not None:
                writer.close()
        if remaining:
            raise RuntimeError("source ended before requested row count")
        temporary.replace(args.output)
        metadata = {"source": args.source, "source_rows": parquet.metadata.num_rows,
                    "source_bytes": source.length, "sample_rows": args.rows,
                    "corpus_description": CORPUS_DESCRIPTION,
                    "corpus_description_source": CORPUS_DESCRIPTION_SOURCE,
                    "selection": "first rows in part_000 file order, matching SearchBench smoke selection",
                    "source_columns": [body_name], "sample_columns": ["Body"],
                    "selected_row_groups": groups, "downloaded_bytes": source.bytes_read,
                    "parquet_bytes": args.output.stat().st_size, "sha256": common.sha256(args.output),
                    "searchbench_revision": SEARCHBENCH_REVISION}
        args.output.with_suffix(".metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
        print(json.dumps(metadata, indent=2), flush=True)
    finally:
        source.close()
        if temporary is not None and temporary.exists():
            temporary.unlink()


def expected_results(data):
    import pyarrow.parquet as pq
    words = re.compile(r"[A-Za-z0-9]+")
    ids = {name: [] for name, *_ in CASES}
    vocabulary = set()
    nulls = 0
    count = 0
    for batch in pq.ParquetFile(data).iter_batches(columns=["Body"]):
        for body in batch.column(0).to_pylist():
            if body is None:
                nulls += 1
                tokens = []
            else:
                tokens = [token.lower() for token in words.findall(body)]
                vocabulary.update(tokens)
            for name, operation, kind, pattern, _ in CASES:
                if kind == "term":
                    match = pattern in tokens
                elif pattern.startswith("%") and pattern.endswith("%"):
                    match = any(pattern[1:-1] in token for token in tokens)
                elif pattern.startswith("%"):
                    match = any(token.endswith(pattern[1:]) for token in tokens)
                else:
                    match = any(token.startswith(pattern[:-1]) for token in tokens)
                if match:
                    ids[name].append(count)
            count += 1
    expected = {}
    for name, operation, *_ in CASES:
        rows = [(len(ids[name]),)] if operation == "count" else [(row_id,) for row_id in ids[name]]
        expected[name] = {"matching_rows": len(ids[name]), "sha256": common.result_digest(rows)}
    return expected, {"sample_rows": count, "null_bodies": nulls,
                      "distinct_ascii_lower_tokens": len(vocabulary)}


def statements(mode):
    indexed = mode != "scan"
    for name, operation, kind, pattern, source_query in CASES:
        if indexed:
            filter_sql = (f"Body @@ '{pattern}'" if kind == "term" and mode != "ngram"
                          else f"Body @@ ts_like('{pattern}')")
            relation = "otel_logs_idx"
        else:
            comparison = f"token = '{pattern}'" if kind == "term" else f"token LIKE '{pattern}'"
            filter_sql = ("array_length(list_filter(split_by_non_alpha(Body, case := 'lower', "
                          f"break := 'ascii'), token -> {comparison}), 1) > 0")
            relation = "otel_logs"
        projection = "count(*)" if operation == "count" else "id"
        order = "" if operation == "count" else " ORDER BY id"
        yield name, operation, f"SELECT {projection} FROM {relation} WHERE {filter_sql}{order}", source_query


def run_mode(args, binary, mode, expected):
    from psycopg import sql
    port = common.free_port()
    datadir = Path(tempfile.mkdtemp(prefix=f"boffa-fm-otel-{mode}-"))
    result = {"mode": mode, "binary": str(binary), "binary_sha256": common.sha256(binary),
              "started_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              "load_average_before": list(os.getloadavg()), "queries": []}
    process = None
    try:
        with (args.output.parent / f"{mode}.server.log").open("w") as log:
            process = subprocess.Popen([str(binary), str(datadir),
                                        f"--listen=postgres://127.0.0.1:{port}"],
                                       stdout=log, stderr=subprocess.STDOUT)
            with common.connect(process, port) as connection:
                connection.execute(f"SET threads = {args.threads}")
                connection.execute("SET statement_timeout = '120s'")
                connection.execute("SET preserve_insertion_order = false")
                connection.execute(sql.SQL("CREATE VIEW otel_logs AS SELECT file_row_number AS id, Body "
                                           "FROM read_parquet({}, file_row_number = true)")
                                   .format(sql.Literal(str(args.data))))
                start = time.perf_counter()
                if mode != "scan":
                    analyzer = (f"generate_wildcard_ngrams({NATIVE_ANALYZER}, 3)"
                                if mode == "ngram" else NATIVE_ANALYZER)
                    features = "frequency, position" if mode == "ngram" else "frequency, norm, position"
                    connection.execute(f"CREATE TEXT SEARCH DICTIONARY otel_en AS {analyzer} "
                                       f"WITH ({features})")
                    result["analyzer"] = analyzer
                    result["features"] = features.split(", ")
                    connection.execute("CREATE TABLE otel_logs_idx (id BIGINT, Body VARCHAR) "
                                       "WITH (storage = 'search', refresh_interval = 0, compaction_interval = 0)")
                    connection.execute("CREATE INDEX otel_logs_search_inv ON otel_logs_idx "
                                       "USING inverted (id, Body otel_en)")
                    connection.execute("INSERT INTO otel_logs_idx SELECT * FROM otel_logs")
                    connection.execute("VACUUM (REFRESH_TABLE) otel_logs_idx")
                result["ingest_and_index_seconds"] = time.perf_counter() - start
                result["before_queries"] = common.resident_bytes(process.pid)
                attempts = 1 if args.verify_only else args.tries
                for name, operation, query, source_query in statements(mode):
                    timings = []
                    counters = []
                    for _ in range(attempts):
                        before = common.process_counters(process.pid)
                        started = time.perf_counter()
                        rows = connection.execute(query).fetchall()
                        timings.append((time.perf_counter() - started) * 1000)
                        after = common.process_counters(process.pid)
                        counters.append({key: after[key] - value for key, value in before.items()})
                        digest = common.result_digest(rows)
                        if digest != expected[name]["sha256"]:
                            raise RuntimeError(f"result disagrees with ASCII-token oracle: {mode} {name}")
                    record = {"name": name, "source_query": source_query, "operation": operation,
                              "sql": query, "matching_rows": expected[name]["matching_rows"],
                              "returned_rows": len(rows), "sha256": digest,
                              "plan": connection.execute("EXPLAIN " + query).fetchall()}
                    if operation == "count":
                        record["count"] = rows[0][0]
                    if not args.verify_only:
                        record.update({"first_ms": timings[0], "warm_ms": timings[1:],
                                       "warm_median_ms": statistics.median(timings[1:]),
                                       "process_counters": counters})
                    if mode == "fm":
                        record["fm_index_serialized_bytes"] = int(connection.execute(
                            "SELECT COALESCE(sum(value), 0) FROM sdb_metrics "
                            "WHERE metric = 'fm_index_serialized_bytes'").fetchone()[0])
                    result["queries"].append(record)
                    print(f"{mode} {name}: {record.get('warm_median_ms', 'verified')} "
                          f"ms, {record['matching_rows']} matches", flush=True)
                metric_cursor = connection.execute("SELECT * FROM sdb_metrics WHERE metric IN "
                                                   "('index_size', 'fm_index_serialized_bytes')")
                columns = [column.name for column in metric_cursor.description]
                metric_rows = [dict(zip(columns, row)) for row in metric_cursor.fetchall()]
                identities = connection.execute("SELECT oid, relname, relkind FROM pg_class "
                                                "WHERE relname IN ('otel_logs_idx', 'otel_logs_search_inv')").fetchall()
                result["relation_identities"] = identities
                result["metrics"] = metric_rows
                result["index_size_metric_rows"] = [row for row in metric_rows if row["metric"] == "index_size"]
                result["index_size_metric_sum_bytes"] = sum(int(row["value"]) for row in metric_rows
                                                           if row["metric"] == "index_size")
                result["fm_index_serialized_bytes"] = sum(int(row["value"]) for row in metric_rows
                                                          if row["metric"] == "fm_index_serialized_bytes")
                result["after_queries"] = common.resident_bytes(process.pid)
                connection.execute("CHECKPOINT")
                result["database_directory_bytes"] = sum(path.stat().st_size for path in datadir.rglob("*")
                                                          if path.is_file())
                if mode == "fm" and result["fm_index_serialized_bytes"] == 0:
                    raise RuntimeError("FM path was not exercised")
                result["load_average_after"] = list(os.getloadavg())
    finally:
        if process is not None and process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=30)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=10)
        shutil.rmtree(datadir)
    return result


def run(args):
    if args.threads < 1 or (not args.verify_only and args.tries < 3):
        raise ValueError("positive thread count and at least three timed attempts required")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    expected, statistics_ = expected_results(args.data)
    report = {"data": str(args.data), "data_bytes": args.data.stat().st_size,
              "data_sha256": common.sha256(args.data), "query_source": QUERY_SOURCE,
              "searchbench_revision": SEARCHBENCH_REVISION, "timed": not args.verify_only,
              "tries": args.tries, "threads": args.threads, "uname": list(os.uname()),
              "logical_cpus": os.cpu_count(),
              "analyzer": NATIVE_ANALYZER, "features": ["frequency", "norm", "position"],
              "corpus_description": CORPUS_DESCRIPTION,
              "corpus_description_source": CORPUS_DESCRIPTION_SOURCE,
              "ngram_adaptation": "same tokenization followed by wildcard 3grams; norm unsupported; "
                                  "exact term control uses ts_like('error') without wildcard; "
                                  "only count/ID predicates evaluated, without ranking",
              "schema_adaptation": "reduced search-backed table: sample row ordinal id BIGINT, Body VARCHAR; "
                                   "native Body analyzer retained; no ranking, full-row projection, or joins",
              "scan_semantics": "same ASCII alphanumeric tokenization/lowercasing, evaluated as a scalar scan",
              "space_accounting": "source sample Parquet shared; search-backed tables ingest Body and id; "
                                  "full metric identity rows retained without deduplication; "
                                  "database_directory_bytes measured separately",
              "data_statistics": statistics_, "expected": expected, "modes": []}
    metadata = args.data.with_suffix(".metadata.json")
    if metadata.exists():
        report["data_provenance"] = json.loads(metadata.read_text())
    for binary, mode in [(args.baseline, "scan"), (args.baseline, "native"),
                         (args.candidate, "fm"), (args.baseline, "ngram")]:
        report["modes"].append(run_mode(args, binary, mode, expected))
        args.output.write_text(json.dumps(report, indent=2, default=str) + "\n")


def main():
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)
    sample = commands.add_parser("prepare")
    sample.add_argument("--source", default=SOURCE)
    sample.add_argument("--rows", type=int, default=100000)
    sample.add_argument("--output", type=Path, required=True)
    sample.set_defaults(action=prepare)
    evaluate = commands.add_parser("run")
    evaluate.add_argument("--baseline", type=lambda value: Path(value).resolve(), required=True)
    evaluate.add_argument("--candidate", type=lambda value: Path(value).resolve(), required=True)
    evaluate.add_argument("--data", type=lambda value: Path(value).resolve(), required=True)
    evaluate.add_argument("--output", type=Path, required=True)
    evaluate.add_argument("--tries", type=int, default=7)
    evaluate.add_argument("--threads", type=int, default=1)
    evaluate.add_argument("--verify-only", action="store_true")
    evaluate.set_defaults(action=run)
    args = parser.parse_args()
    args.action(args)


if __name__ == "__main__":
    main()
