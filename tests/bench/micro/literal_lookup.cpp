// ============================ lookup loops ============================
// One lookup per benchmark iteration -> reported Time is ns/lookup (+ a
// constant index/mask shared by every structure, so comparisons are fair).
template<std::size_t N>
void RunLinearCS(benchmark::State& s, const std::string_view (&a)[N],
                 const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    std::string_view key = q[i];
    bool found = false;
    for (std::size_t j = 0; j < N; ++j) {
      if (a[j] == key) {
        found = true;
        break;
      }
    }
    benchmark::DoNotOptimize(found);
  }
}
template<std::size_t N>
void RunLinearCI(benchmark::State& s, const std::string_view (&a)[N],
                 const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    std::string_view key = q[i];
    bool found = false;
    for (std::size_t j = 0; j < N; ++j) {
      if (StringUtil::CIEquals(a[j], key)) {
        found = true;
        break;
      }
    }
    benchmark::DoNotOptimize(found);
  }
}
void RunSortedCS(benchmark::State& s, const std::vector<std::string_view>& v,
                 const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    bool found = std::binary_search(v.begin(), v.end(), std::string_view(q[i]));
    benchmark::DoNotOptimize(found);
  }
}
void RunSortedCI(benchmark::State& s, const std::vector<std::string_view>& v,
                 const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    std::string_view key = q[i];
    auto it = std::lower_bound(v.begin(), v.end(), key,
                               [](std::string_view x, std::string_view y) {
                                 return StringUtil::CILessThan(x, y);
                               });
    bool found = it != v.end() && StringUtil::CIEquals(*it, key);
    benchmark::DoNotOptimize(found);
  }
}
// Look up the std::string key directly: each hash set uses ITS OWN default
// hash/eq for CS, and DuckDB's CIHash/CIEquals for CI. count(const string&) is
// exact-key (no transparency needed), zero-copy.
template<class SetT>
void RunHash(benchmark::State& s, const SetT& set,
             const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    benchmark::DoNotOptimize(set.count(q[i]));
  }
}
template<class SetT>
void RunTrivCs(benchmark::State& s, const SetT& set,
               const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    benchmark::DoNotOptimize(set.Contains(std::string_view(q[i])));
  }
}
template<class SetT>
void RunTrivCi(benchmark::State& s, const SetT& set,
               const std::vector<std::string>& q) {
  std::size_t i = 0, m = q.size() - 1;
  for (auto _ : s) {
    i = (i + 1) & m;
    benchmark::DoNotOptimize(set.ContainsICase(std::string_view(q[i])));
  }
}
