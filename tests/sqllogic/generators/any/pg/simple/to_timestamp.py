t = Test("to_timestamp and to_date, from PostgreSQL's horology tests: each text read with its "
         "format, fractional seconds of every precision, formats taken from a column, a read in "
         "another time zone and the texts PostgreSQL rejects, every answer recorded from "
         "PostgreSQL.")
t.statement("SET TimeZone = 'UTC'")
t.section("Each text read with its format.")
for expression in READS:
    t.query(f"SELECT {expression} AS a", ["a"])
t.section("Fractional seconds of every precision.")
for expression in FRACTIONS:
    t.query(f"SELECT i, {expression} AS a FROM generate_series(1, 6) i ORDER BY i", ["i", "a"], 6)
t.section("Formats and texts taken from a column.")
t.query("SELECT to_timestamp(t, f) AS ts FROM (VALUES ('2020-01-02', 'YYYY-MM-DD'), "
        "('2020-01-02', 'YYYY-MM-DD'), ('03/04/2021', 'MM/DD/YYYY'), ('2022', 'YYYY')) v(t, f) "
        "ORDER BY ts", ["ts"], 4)
t.query("SELECT to_date(t, 'YYYY-MM-DD') AS d FROM (VALUES ('2020-01-02'), ('2021-03-04')) v(t) "
        "ORDER BY d", ["d"], 2)
t.section("Texts PostgreSQL rejects.")
for expression in REJECTED:
    t.query(f"SELECT {expression} AS a", ["a"])
t.section("A read in another time zone.")
t.statement("SET TimeZone = 'America/New_York'")
for expression in NEW_YORK:
    t.query(f"SELECT {expression} AS a", ["a"])
t.statement("SET TimeZone = 'UTC'")
t.write()
