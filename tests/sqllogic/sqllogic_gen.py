import os
import random
import sys
import textwrap

RECORDED = "<recorded>"
RECORDED_ROWS = "<recorded rows>"
PART = "<part>"
HERE = os.path.dirname(os.path.abspath(__file__))


def lit(text):
    return text.replace("'", "''")


class Test:
    def __init__(self, about, seed=None):
        self.rng = random.Random(seed)
        self._lines = []
        generator = os.path.relpath(os.path.abspath(sys.argv[0]), HERE)
        recorded = os.path.basename(generator)[:-len(".py")] + ".recorded"
        note = (f"Generated by {generator} on every run, with the server's "
                f"answers from {recorded} next to it: edit the generator, "
                "not this file.")
        for paragraph in (note, about):
            self._lines += textwrap.wrap(paragraph, 78, initial_indent="# ",
                                         subsequent_indent="# ")
        self._lines.append("")

    def part(self):
        self._lines += [PART, ""]

    def parts(self, items, size):
        for start in range(0, len(items), size):
            self.part()
            yield items[start:start + size]

    def section(self, title):
        self._lines += textwrap.wrap(title, 78, initial_indent="# --- ",
                                     subsequent_indent="# ")
        self._lines.append("")

    def control(self, setting):
        self._lines += [f"control {setting}", ""]

    def _condition(self, onlyif, skipif):
        self._lines += [f"onlyif {onlyif}"] if onlyif else []
        self._lines += [f"skipif {skipif}"] if skipif else []

    def connection(self, name):
        self._lines.append(f"connection {name}")

    def statement(self, sql, kind="statement ok", onlyif=None, skipif=None):
        self._condition(onlyif, skipif)
        self._lines += [kind, sql, ""]

    def dictionary(self, name, definition):
        self.statement(f"CREATE TEXT SEARCH DICTIONARY {name} AS {definition}")

    def table(self, name, columns, search=False):
        storage = " WITH (storage = 'search')" if search else ""
        self.statement(f"CREATE TABLE {name} ({columns}){storage}")

    def insert(self, table, rows, chunk=100):
        rows = list(rows)
        step = chunk or len(rows)
        for start in range(0, len(rows), step):
            values = ",\n    ".join(rows[start:start + step])
            self.statement(f"INSERT INTO {table} VALUES\n    {values}")

    def index(self, name, table, keys, include=None):
        included = f" INCLUDE ({include})" if include else ""
        self.statement(
            f"CREATE INDEX {name} ON {table} USING inverted ({keys}){included}")

    def refresh(self, table):
        self.statement(f"VACUUM (REFRESH_TABLE) {table}")

    def query(self, sql, columns=None, rows=1, onlyif=None, skipif=None):
        header = [] if columns is None else ["\t".join(columns)]
        if columns is None or rows is None:
            rows = [[RECORDED_ROWS]]
        elif isinstance(rows, int):
            rows = [[RECORDED] * len(columns)] * rows
        self._condition(onlyif, skipif)
        self._lines += ["query", sql, "----", *header,
                        *("\t".join(map(str, row)) for row in rows), ""]

    def expect(self, sql, columns, rows, kind="query"):
        self._lines += [kind, sql, "----", "\t".join(columns),
                        *("\t".join(map(str, row)) for row in rows), ""]

    def error(self, sql, message, onlyif=None, skipif=None):
        self._condition(onlyif, skipif)
        self._lines += [f"statement error {message}", sql, ""]

    def same_rows(self, actual, expected):
        self._lines += [
            "query",
            f"SELECT (SELECT count(*) FROM ({expected})) AS matches, "
            f"(SELECT count(*) FROM (({actual} EXCEPT {expected}) UNION ALL "
            f"({expected} EXCEPT {actual}))) AS mismatches",
            "----", "matches\tmismatches", f"{RECORDED}\t0", ""]

    def same_scores(self, actual, expected):
        self._lines += [
            "query",
            f"SELECT count(*) AS mismatches FROM ({actual}) a FULL JOIN "
            f"({expected}) b USING (id) WHERE a.s IS DISTINCT FROM b.s",
            "----", "mismatches", "0", ""]

    def write(self):
        sys.stdout.write("\n".join(self._lines) + "\n")
